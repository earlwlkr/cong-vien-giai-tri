export type SpriteName = keyof typeof SPRITES;
export const SPRITE_NAMES = Object.keys(SPRITES) as SpriteName[];

export function isSprite(name: string): name is SpriteName {
  return name in SPRITES;
}

const canvasCache = new Map<string, HTMLCanvasElement>();
/** Rasterised sprite, `scale` screen pixels per sprite pixel. */
export function spriteCanvas(name: SpriteName, scale = 4): HTMLCanvasElement {
  const key = name + "@" + scale;
  let c = canvasCache.get(key);
  if (c) return c;
  const rows = SPRITES[name];
  c = document.createElement("canvas");
  c.width = rows[0].length * scale;
  c.height = rows.length * scale;
  const g = c.getContext("2d")!;
  rows.forEach((row, y) => {
    for (let x = 0; x < row.length; x++) {
      const col = PAL[row[x]];
      if (!col) continue;
      g.fillStyle = col;
      g.fillRect(x * scale, y * scale, scale, scale);
    }
  });
  canvasCache.set(key, c);
  return c;
}

const urlCache = new Map<string, string>();
export function spriteURL(name: SpriteName): string {
  let u = urlCache.get(name);
  if (!u) urlCache.set(name, (u = spriteCanvas(name, 4).toDataURL()));
  return u;
}

/** Draws a sprite centred at (cx, cy), `size` px square, crisp. */
export function drawSprite(g: CanvasRenderingContext2D, name: SpriteName, cx: number, cy: number, size: number) {
  const prev = g.imageSmoothingEnabled;
  g.imageSmoothingEnabled = false;
  const src = spriteCanvas(name, Math.max(1, Math.ceil(size / 16)));
  g.drawImage(src, Math.round(cx - size / 2), Math.round(cy - size / 2), size, size);
  g.imageSmoothingEnabled = prev;
}

export function spriteEl(name: SpriteName, cls = "spr"): HTMLImageElement {
  const img = document.createElement("img");
  img.className = cls;
  img.src = spriteURL(name);
  img.alt = "";
  img.draggable = false;
  return img;
}

/**
 * Fills `el` with text where `{name}` tokens become inline sprites.
 * Only use with app-authored strings (never raw chat input).
 */
export function setRich(el: HTMLElement, text: string) {
  el.replaceChildren();
  const re = /\{([a-z]+)\}/g;
  let last = 0;
  for (let m; (m = re.exec(text)); ) {
    if (!isSprite(m[1])) continue;
    if (m.index > last) el.append(text.slice(last, m.index));
    el.append(spriteEl(m[1]));
    last = m.index + m[0].length;
  }
  if (last < text.length) el.append(text.slice(last));
}

/** Replaces every `<i data-s="name">` placeholder in the document with its sprite. */
export function hydrateSprites(root: ParentNode = document) {
  root.querySelectorAll<HTMLElement>("i[data-s]").forEach((i) => {
    const n = i.dataset.s!;
    if (isSprite(n)) i.replaceWith(spriteEl(n, ["spr", ...i.classList].join(" ")));
  });
}
